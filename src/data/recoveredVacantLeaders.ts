export function filterValidDynamicLeaders(rawList: Leader[]): Leader[] {
  return (Array.isArray(rawList) ? rawList : []).filter(
    (l) => Boolean(l && ((l.name || '').trim() || (l.role || '').trim()))
  );
}

export function findMissingVacantLeaders(existing: Leader[]): Leader[] {
  const existingIds = new Set(
    (Array.isArray(existing) ? existing : [])
      .map((l) => (l?.id || '').trim())
      .filter(Boolean)
  );
  return RECOVERED_VACANT_LEADERS.filter((item) => !existingIds.has(String(item.id)));
}

export function mergeMissingVacantLeaders(existing: Leader[]): {
  merged: Leader[];
  addedCount: number;
} {
  const base = Array.isArray(existing) ? [...existing] : [];
  const missing = findMissingVacantLeaders(base);
  if (missing.length === 0) {
    return { merged: base, addedCount: 0 };
  }
  return {
    merged: [...base, ...missing],
    addedCount: missing.length,
  };
}
